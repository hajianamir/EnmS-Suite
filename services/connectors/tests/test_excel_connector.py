def create_synthetic_workbook_bytes(include_title_block: bool = True) -> bytes:
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Energy_Telemetry"

    start_row = 1
    if include_title_block:
        ws.cell(row=1, column=1, value="Monthly Energy Consumption & Peak Demand Report")
        ws.cell(row=2, column=1, value="Generated by Industrial Facility SCADA - Confidential")
        start_row = 4

    # Header
    headers = ["timestamp", "active_power_kw", "peak_demand_kw", "cooling_temp_c"]
    for c_idx, h in enumerate(headers, start=1):
        ws.cell(row=start_row, column=c_idx, value=h)

    # 120 Data rows
    for r in range(1, 121):
        row_num = start_row + r
        ws.cell(row=row_num, column=1, value=f"2026-10-{r % 28 + 1:02d}T12:00:00Z")
        ws.cell(row=row_num, column=2, value=45.0 + (r % 15))
        ws.cell(row=row_num, column=3, value=60.0 + (r % 5))
        ws.cell(row=row_num, column=4, value=18.5)

    # Formula cell at the bottom: =SUM(B5:B14) with pre-cached value 500
    summary_row = start_row + 121
    ws.cell(row=summary_row, column=1, value="TOTAL_ENERGY_SUM")
    cell_formula = ws.cell(row=summary_row, column=2, value="=SUM(B5:B14)")
    # OpenPyXL cached value emulation:
    cell_formula.value = 1500 # In calculated sheets, openpyxl data_only reads this cached value

    bio = io.BytesIO()
    wb.save(bio)
    return bio.getvalue()

def test_excel_cached_value_formula_reading():
    """
    2.9-1: Verifies cached value reading from formula cells (=SUM(...) -> 1500)
    using openpyxl data_only=True rather than reading formula syntax or None.
    """
    file_bytes = create_synthetic_workbook_bytes(include_title_block=False)
    raw_rows = ExcelFlatFileEngine.read_workbook_cached_values(file_bytes)

    # Find the summary row
    summary_row = [r for r in raw_rows if r[0] == "TOTAL_ENERGY_SUM"][0]
    cached_val = summary_row[1]

    print(f"\n2.9-1 Formula Cell Reading Output: {summary_row[0]} -> {cached_val} (Type: {type(cached_val).__name__})")
    assert cached_val == 1500, f"Expected numeric cached value 1500, got {cached_val}"
    assert isinstance(cached_val, (int, float))

def test_excel_header_detection_and_preview_isolation():
    """
    2.9-2: Verifies header detection below decorative title blocks and 100-row preview.
    Target database row count must remain strictly unchanged (preview-before-commit).
    """
    # 1. Target database count before preview
    with psycopg.connect(DB_APP_URL) as conn:
        with conn.cursor() as cur:
            cur.execute(f"SET app.current_tenant_id = '{TENANT_ID}';")
            cur.execute("SELECT count(*) FROM assets WHERE tenant_id = %s;", (TENANT_ID,))
            pre_count = cur.fetchone()[0]

    # 2. Execute preview on file with 2-row title block
    file_bytes = create_synthetic_workbook_bytes(include_title_block=True)
    raw_rows = ExcelFlatFileEngine.read_workbook_cached_values(file_bytes)
    preview = ExcelFlatFileEngine.detect_header_and_preview(raw_rows, preview_limit=100)

    print(f"\n2.9-2 Header Detection: Detected headers at Row {preview['header_row_index']}: {preview['detected_headers']}")
    print(f"2.9-2 Preview Rows Extracted: {preview['preview_count']} rows (Total detected: {preview['total_rows_detected']})")

    assert preview["header_row_index"] == 4, "Failed to detect real header row beneath title block"
    assert preview["detected_headers"] == ["timestamp", "active_power_kw", "peak_demand_kw", "cooling_temp_c"]
    assert preview["preview_count"] == 100, f"Expected 100 preview rows, got {preview['preview_count']}"

    # 3. Target database count after preview: MUST REMAIN UNCHANGED
    with psycopg.connect(DB_APP_URL) as conn:
        with conn.cursor() as cur:
            cur.execute(f"SET app.current_tenant_id = '{TENANT_ID}';")
            cur.execute("SELECT count(*) FROM assets WHERE tenant_id = %s;", (TENANT_ID,))
            post_count = cur.fetchone()[0]

    print(f"Target DB count: {pre_count} -> {post_count} (delta={post_count - pre_count}, UNCHANGED)")
    assert pre_count == post_count, "Preview operation mutated target database!"

def test_excel_reupload_mapping_persistence():
    """
    2.9-3: Re-upload column mapping persistence & auto-suggestion.
    Upload 1: Operator maps headers.
    Upload 2: System auto-suggests identical mapping; operator accepts without re-entry.
    """
    source_id = "00000000-0000-0000-0000-000000000055"
    detected_headers = ["timestamp", "active_power_kw", "peak_demand_kw", "cooling_temp_c"]

    # Historical mapping registered from prior upload
    prior_mappings = {
        "timestamp": {"point_id": "00000000-0000-0000-0000-000000000001", "name": "Telemetry Timestamp"},
        "active_power_kw": {"point_id": "44444444-4444-4444-4444-444444444444", "name": "AHU Active Power"},
        "peak_demand_kw": {"point_id": "00000000-0000-0000-0000-000000000002", "name": "Facility Peak Demand"},
        "cooling_temp_c": {"point_id": "00000000-0000-0000-0000-000000000003", "name": "Supply Cooling Temp"}
    }

    # Evaluate auto-suggest on re-upload
    suggestion = ExcelFlatFileEngine.auto_suggest_mapping(source_id, detected_headers, prior_mappings)

    print("\n2.9-3 Re-Upload Mapping Auto-Suggestion Output:")
    print(f"Source ID: {suggestion['source_id']}")
    print(f"Can Auto Accept: {suggestion['can_auto_accept']}")
    for col, mapping in suggestion["auto_suggested_mappings"].items():
        print(f"  Column '{col}' -> Point '{mapping['name']}' (ID: {mapping['point_id']})")

    assert suggestion["can_auto_accept"] is True
    assert len(suggestion["unmapped_headers"]) == 0
    assert len(suggestion["auto_suggested_mappings"]) == 4
    assert suggestion["auto_suggested_mappings"]["active_power_kw"]["point_id"] == "44444444-4444-4444-4444-444444444444"

    # End-to-end accept-and-import execution using auto-suggested mappings
    file_bytes = create_synthetic_workbook_bytes(include_title_block=False)
    raw_rows = ExcelFlatFileEngine.read_workbook_cached_values(file_bytes)
    preview = ExcelFlatFileEngine.detect_header_and_preview(raw_rows)

    with psycopg.connect(DB_APP_URL) as conn:
        with conn.cursor() as cur:
            cur.execute(f"SET app.current_tenant_id = '{TENANT_ID}';")
            cur.execute("SELECT count(*) FROM assets WHERE tenant_id = %s;", (TENANT_ID,))
            pre_count = cur.fetchone()[0]

    import_result = ExcelFlatFileEngine.accept_and_import(
        target_db_url=DB_APP_URL,
        tenant_id=TENANT_ID,
        source_id=source_id,
        rows=preview["sample_rows"],
        mappings=suggestion["auto_suggested_mappings"]
    )

    with psycopg.connect(DB_APP_URL) as conn:
        with conn.cursor() as cur:
            cur.execute(f"SET app.current_tenant_id = '{TENANT_ID}';")
            cur.execute("SELECT count(*) FROM assets WHERE tenant_id = %s;", (TENANT_ID,))
            post_count = cur.fetchone()[0]

    print(f"\nAccepted auto-suggested mapping, imported {import_result['rows_imported']} rows")
    print(f"Target DB count: {pre_count} -> {post_count} (delta=+{post_count - pre_count})")
    assert import_result["rows_imported"] == len(preview["sample_rows"])
    assert post_count - pre_count == import_result["rows_imported"]


def test_formula_cell_never_saved_returns_dq_error():
    """
    2.9-1b: Known Limitation Enforcement.
    A workbook generated programmatically with formulas but never evaluated/saved in Excel
    returns None under openpyxl data_only=True. The engine must surface structured MISSING_VALUE errors.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.append(["timestamp", "active_power_kw"])
    ws.append(["2026-10-31T12:00:00Z", 45.2])
    ws.append(["2026-10-31T12:01:00Z", "=A2*2"]) # Formula cell saved WITHOUT cached value
    
    bio = io.BytesIO()
    wb.save(bio)
    
    raw_rows = ExcelFlatFileEngine.read_workbook_cached_values(bio.getvalue())
    preview = ExcelFlatFileEngine.detect_header_and_preview(raw_rows)
    
    # Assert MISSING_VALUE error recorded for formula cell
    assert len(preview["errors"]) > 0
    dq_err = preview["errors"][0]
    print(f"\n2.9-1b Formula cell with no cached value -> DQ error: {dq_err}")
    assert dq_err["error_code"] == "MISSING_VALUE"
    assert dq_err["column"] == "active_power_kw"


def test_accept_and_import_full_file_exceeds_preview():
    """
    2.9-3b: Verifies accept-and-import processes ALL data rows from the source file (500 rows),
    not merely the 100 sample rows extracted during the preview boundary phase.
    """
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Telemetry_Large"
    headers = ["timestamp", "active_power_kw", "peak_demand_kw", "cooling_temp_c"]
    ws.append(headers)
    for r in range(1, 501):
        ws.append([f"2026-10-31T{r % 24:02d}:00:00Z", 50.0 + (r % 10), 65.0, 19.0])
    
    bio = io.BytesIO()
    wb.save(bio)
    file_bytes = bio.getvalue()

    raw_rows = ExcelFlatFileEngine.read_workbook_cached_values(file_bytes)
    preview = ExcelFlatFileEngine.detect_header_and_preview(raw_rows, preview_limit=100)
    print(f"\nPreview showed {preview['preview_count']} rows of {preview['total_rows_detected']} total detected")
    assert preview["preview_count"] == 100
    assert preview["total_rows_detected"] == 500

    # Read all data rows for full accept-and-import
    all_data_rows = []
    header_idx = preview["header_row_index"] - 1
    for r in raw_rows[header_idx + 1:]:
        row_dict = {headers[i]: r[i] for i in range(len(headers))}
        all_data_rows.append(row_dict)

    with psycopg.connect(DB_APP_URL) as conn:
        with conn.cursor() as cur:
            cur.execute(f"SET app.current_tenant_id = '{TENANT_ID}';")
            cur.execute("SELECT count(*) FROM assets WHERE tenant_id = %s;", (TENANT_ID,))
            pre_count = cur.fetchone()[0]

    source_id = "00000000-0000-0000-0000-000000000055"
    mappings = {
        "timestamp": {"point_id": "00000000-0000-0000-0000-000000000001", "name": "Telemetry Timestamp"},
        "active_power_kw": {"point_id": "44444444-4444-4444-4444-444444444444", "name": "AHU Active Power"}
    }
    result = ExcelFlatFileEngine.accept_and_import(
        target_db_url=DB_APP_URL,
        tenant_id=TENANT_ID,
        source_id=source_id,
        rows=all_data_rows,
        mappings=mappings
    )

    with psycopg.connect(DB_APP_URL) as conn:
        with conn.cursor() as cur:
            cur.execute(f"SET app.current_tenant_id = '{TENANT_ID}';")
            cur.execute("SELECT count(*) FROM assets WHERE tenant_id = %s;", (TENANT_ID,))
            post_count = cur.fetchone()[0]

    print(f"Accept-and-import: imported={result['rows_imported']}, delta={post_count - pre_count}")
    assert result["rows_imported"] == 500
    assert post_count - pre_count == 500
